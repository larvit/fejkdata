const shippedIndexFile = "shippedindex.go"

// newShippedWhole loads every shipped category in New, as a --data-path load does, so a test
// reads the whole shipped tree.
func newShippedWhole(t testing.TB, opts ...Option) *Generator {
	t.Helper()
	data, err := fs.Sub(shippedFS, "data")
	if err != nil {
		t.Fatal(err)
	}
	f, err := New(append([]Option{WithoutShippedData(), WithDataFS(data)}, opts...)...)
	if err != nil {
		t.Fatalf("New() = %v", err)
	}
	return f
}

// loadedCategories is the dot path of every category f has parsed and linked.
func loadedCategories(f *Generator) []string {
	var out []string
	for _, s := range categorySites(&f.root) {
		out = append(out, s.path)
	}
	return out
}

// REGENERATE=1, which go generate sets, rewrites the index.
func TestShippedIndexIsCurrent(t *testing.T) {
	got, err := shippedIndexSource(newShippedWhole(t))
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv("REGENERATE") == "1" {
		if err := os.WriteFile(shippedIndexFile, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	file, err := os.ReadFile(shippedIndexFile)
	if err != nil {
		t.Fatal(err)
	}
	want, err := format.Source(file) // docs/decisions.md#the-format-check-runs-on-the-latest-go-only
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != string(want) {
		t.Fatalf("%s is stale for data/; regenerate it: docker compose run --rm --user \"$(id -u):$(id -g)\" generate", shippedIndexFile)
	}
}

func shippedIndexSource(whole *Generator) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate. DO NOT EDIT.\n\npackage fejkdata\n\nvar shippedIndex = map[string]shippedEntry{\n")
	for _, s := range categorySites(&whole.root) {
		fmt.Fprintf(&b, "%q: {", s.path)
		if t, isTable := s.n.(*table); isTable && t.parentIndex >= 0 {
			fmt.Fprintf(&b, "parent: %q, ", t.header[t.parentIndex])
		}
		ps := paths(s.n)
		sort.Strings(ps)
		fmt.Fprintf(&b, "paths: %#v},\n", ps)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

